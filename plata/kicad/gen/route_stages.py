"""Этапы трассировки (route.yml). Каждый запуск — один этап: небольшая задача, но на всей плате.

Как устроен этап:
- трассировщик видит ВСЮ плату: все детали, все площадки, все уже проложенные дорожки (препятствия);
- разводит только цепи этапа и цепи, уже начатые на прошлых этапах; площадки остальных цепей для него —
  препятствия без цепи (их очередь позже);
- прошлые дорожки НЕ закреплены: если новой цепи не пройти, он может переложить старую — тупика нет;
- результат сохраняется в ветку route-state отдельным коммитом: любой этап можно посмотреть и откатить.

Порядок — аудит Codex df4bb5c §5.4: силовые ячейки → выводы на плоскости → Ethernet/USB/кварцы → остальное.
"""
from fnmatch import fnmatchcase

# имя, шаблоны цепей, проходов за запуск, сколько раз можно повторить этап (пока убывает число неразведённых)
STAGES = [
    ('power', ['*/VIN_*', 'VIN_*', '+24V_P', '+5V_LCD?', '*/LCD?_*', '*/P12_*', '*/P5_*', '*/P3_*', '*/EF_*',
               '*/LED_*', '+12V', '+5V', '*VTK_24V', 'MDB_24V', '*EXT_24V', '*SW_VCORE'], 4, 2),
    ('planes', ['GND', '+3V3', '+3V3A'], 3, 2),
    # имена со слешем и без: глобальные LNK_*, SW_*1 — без пути листа (Codex R-002)
    ('fast', ['*ETH_*', '*SW_*', '*LNK_*', '*USB_*', '*/Y?_*', '*_XI', '*_XO'], 5, 2),
    ('rest', ['*'], 15, 6),
]


def names():
    return [s[0] for s in STAGES]


def get(name):
    for s in STAGES:
        if s[0] == name:
            return s
    raise SystemExit('нет этапа ' + name)


def in_stage(net, name):
    """Цепь входит в этап, если подходит под шаблон этого или любого ПРЕДЫДУЩЕГО этапа."""
    for s in STAGES:
        if any(fnmatchcase(net, p) for p in s[1]):
            return True
        if s[0] == name:
            return False
    return False


def next_stage(name, run, before, after):
    """Что запускать следующим: (этап, номер запуска) или None — закончили.
    Первые этапы — по одному запуску (их цепи всё равно доразводятся на следующих этапах);
    «rest» повторяется, пока число неразведённых связей убывает, но не больше заданного числа раз."""
    if name != 'rest':
        return (STAGES[names().index(name) + 1][0], 1)
    if after == 0:
        return None
    progress = before is None or after < before
    return ('rest', run + 1) if (progress and run < get('rest')[3]) else None
